// qq/shared/settings-contract.js
//
// QQ 桥接设置的**唯一清单**。一份数据生成三处：
//   - 宿主半 qq/index.js：Config / BridgeSettings 的 Schema、readSettings() 的归一化、
//     knownSettingKeys()、redactSecretsForDisplay()；
//   - 浏览器半 qq/client/client.js：设置卡片的 FIELDS 与 GROUPS
//     （由 scripts/build-bundle.mjs 序列化注入成 __INJECTED_CONTRACT）；
//   - 设置接口的白名单与状态打码。
//
// 每个字段都是纯数据 + 纯函数，不要 import 任何东西、也不要引用宿主对象：
//   key / label / kind / group / hint / options / step / min / max / default
//   normalize(raw)  读设置时收敛坏值（readSettings 用）
//   schema          生成 Schemastery 节点（type / items / role）
//   secret          状态输出要打码（modelPool 打码每个槽位的 apiKey）
//   check           浏览器半的输入提示（声明式，构建时可序列化）
//   compositionOnly 不参与 Schema/readSettings 生成，仍由 index.js 手写（接线逻辑）
//   idleWeight      不单独输出，聚合成 readSettings().idleWeights
//
// 共 55 项，与 BridgeSettings 的键数一致。

const trimString = (v) => String(v ?? '').trim()
const asBoolean = (v) => v === true
const asBooleanDefaultOn = (v) => v !== false
const clampNumber = (min, max) => (v) => Math.max(min, Math.min(max, Number(v)))
const minNumber = (min) => (v) => Math.max(min, Number(v))
const clampNumberOr = (min, max, fallback) => (v) => Math.max(min, Math.min(max, Number(v) || fallback))
const roundClampNumberOr = (min, max, fallback) => (v) =>
  Math.max(min, Math.min(max, Math.round(Number(v) || fallback)))
const clampProbability = (v) => {
  const n = Number(v)
  return Number.isFinite(n) ? Math.max(0, Math.min(1, n)) : 0.05
}
const stringList = (v) => v.map(String)
const nicknameList = (v) => v.map((n) => String(n)).filter((n) => n !== '')
const adminList = (v) => v.map((x) => String(x ?? '').trim()).filter((x) => x !== '')
const idleWeightNumber = (v) => {
  const n = Number(v)
  return Number.isFinite(n) && n >= 0 ? n : 0
}
/** 与 index.js 的 normalizeModelPool 同一规则：固定 3 个槽位、坏值收敛成空槽。 */
const modelPoolValue = (v) => {
  const rows = Array.isArray(v) ? v : []
  const out = []
  for (let i = 0; i < 3; i += 1) {
    const row = rows[i] && typeof rows[i] === 'object' ? rows[i] : {}
    out.push({
      enabled: row.enabled === true,
      apiUrl: String(row.apiUrl ?? '').trim(),
      apiKey: String(row.apiKey ?? '').trim(),
      modelName: String(row.modelName ?? '').trim(),
    })
  }
  return out
}

